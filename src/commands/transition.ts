function exactSinglePublicationWork(output: ObservationObject): string {
  const works = output.works;
  if (output.memberCount !== 1 || !Array.isArray(works) || works.length !== 1 || typeof works[0] !== "string") {
    throw new UsfError("TRANSITION_SEMANTICS_INCOMPLETE", exitCodes.DOMAIN_FAILURE, "Canonical publication must return exactly one selected work.");
  }
  return works[0];
}

function bindingAwareNativeSelection(root: string, selection: { readonly rootIdentity: string; readonly manifestPath: string }) {
  const graph = loadTransitionContextGraph(root, selection);
  const context = deriveCliTransitionContext(graph, selection.rootIdentity);
  if (context.diagnostics.length !== 0 || context.work === null || context.profile === null) {
    throw new UsfError("CLI_TRANSITION_STALE", exitCodes.CURRENTNESS_FAILURE, "Native completion delegation requires one current selected work context.");
  }
  return Object.freeze({ rootIdentity: context.work, manifestPath: context.binding?.targetManifest ?? selection.manifestPath,
    profile: context.profile, graphDigest: canonicalQuadDigest(graph.quads) });
}

async function withCurrentNativeSelection<T>(
  root: string,
  selection: { readonly rootIdentity: string; readonly manifestPath: string },
  invoke: (nativeSelection: { readonly rootIdentity: string; readonly manifestPath: string }) => Promise<T>,
): Promise<T> {
  const before = bindingAwareNativeSelection(root, selection);
  const output = await invoke({ rootIdentity: before.rootIdentity, manifestPath: before.manifestPath });
  const after = bindingAwareNativeSelection(root, selection);
  if (after.rootIdentity !== before.rootIdentity || after.manifestPath !== before.manifestPath
    || after.profile !== before.profile || after.graphDigest !== before.graphDigest) {
    throw new UsfError("CLI_TRANSITION_STALE", exitCodes.CURRENTNESS_FAILURE, "Binding or selected native completion context changed during delegation.");
  }
  return output;
}

